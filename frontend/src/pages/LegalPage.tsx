import { useQuery } from "@tanstack/react-query";
import { Link } from "react-router-dom";
import { api } from "../lib/api";
import { Card, CardContent } from "../components/ui/card";
import { LoadingState } from "../components/LoadingState";
import { ErrorState } from "../components/ErrorState";

type LegalPayload = {
  title: string;
  updated_at: string;
  notice: string;
  platform_operator_name: string;
  privacy_contact_email: string;
};

export function LegalPage({ kind }: { kind: "privacy" | "terms" }) {
  const legal = useQuery({
    queryKey: ["legal", kind],
    queryFn: () => api.get<LegalPayload>(`/legal/${kind === "privacy" ? "privacy" : "terms"}/`)
  });

  if (legal.isLoading) return <LoadingState />;
  if (legal.isError || !legal.data) return <ErrorState />;

  return (
    <article className="mx-auto max-w-4xl">
      <p className="eyebrow">Правни информации</p>
      <h1 className="mt-2 text-4xl font-semibold md:text-5xl">{legal.data.title}</h1>
      <p className="mt-2 text-muted-foreground">Последно ажурирање: {legal.data.updated_at}</p>
      <Card className="mt-6 rounded-none border-0 border-l-4 border-amber-400 bg-amber-50 shadow-none">
        <CardContent className="p-5 text-amber-950">
          <strong>Нацрт за MVP.</strong> {legal.data.notice}
        </CardContent>
      </Card>
      <div className="mt-10 space-y-10 leading-7 text-foreground">
        {kind === "privacy" ? (
          <PrivacyPolicy
            operatorName={legal.data.platform_operator_name}
            contactEmail={legal.data.privacy_contact_email}
          />
        ) : (
          <TermsOfUse
            operatorName={legal.data.platform_operator_name}
            contactEmail={legal.data.privacy_contact_email}
          />
        )}
      </div>
    </article>
  );
}

